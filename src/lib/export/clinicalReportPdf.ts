import { formatDisplayDateTime } from "../dates/format";
import { buildCrossCheckFingerprint, shortFingerprint } from "./integrityFingerprints";
import type { VerificationReport } from "./verificationReport";

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderIssueList(items: string[]): string {
  if (items.length === 0) {
    return "<p class=\"muted\">No issues detected.</p>";
  }

  const listItems = items.map((item) => `<li>${escapeHtml(item)}</li>`).join("");
  return `<ul>${listItems}</ul>`;
}

function renderPolicySection(report: VerificationReport): string {
  const policy = report.manifest.redactionPolicy;

  if (!policy) {
    return `
      <section class="card" style="margin-top: 20px;">
        <h2>Redaction Policy</h2>
        <p class="muted">No policy metadata was embedded in this verification report.</p>
      </section>`;
  }

  const omittedList =
    policy.translation.omittedFieldLabels.length > 0
      ? renderIssueList(policy.translation.omittedFieldLabels)
      : "<p class=\"muted\">No fields were omitted by policy.</p>";

  return `
      <section class="card" style="margin-top: 20px;">
        <h2>Redaction Policy</h2>
        <p><strong>Policy:</strong> ${escapeHtml(policy.translation.heading)}</p>
        <p>${escapeHtml(policy.translation.summary)}</p>
        <p>${escapeHtml(policy.translation.attachmentHandling)}</p>
        <p>${escapeHtml(policy.translation.metadataAppendixHandling)}</p>
        <p><strong>Omitted by policy:</strong></p>
        ${omittedList}
      </section>`;
}

function renderSecurityFingerprintSection(report: VerificationReport): string {
  return `
      <section class="card" style="margin-top: 20px; border-color: #8a5a00; background: #fff7e6;">
        <h2>Security Fingerprint</h2>
        <p>Use this compact reference to compare the certificate against the JSON verification report and on-screen verifier.</p>
        <p class="mono"><strong>Cross-check:</strong> ${escapeHtml(
          buildCrossCheckFingerprint(report.manifest.integritySeal, report.reportSha256)
        )}</p>
        <p class="mono"><strong>Manifest seal:</strong> ${escapeHtml(shortFingerprint(report.manifest.integritySeal, 4, 5))}</p>
        <p class="mono"><strong>Report checksum:</strong> ${escapeHtml(shortFingerprint(report.reportSha256, 4, 5))}</p>
      </section>`;
}

