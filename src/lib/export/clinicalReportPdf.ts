export function printClinicalVerificationCertificate(report: VerificationReport): void {
  const printWindow = globalThis.open("", "_blank", "noopener,noreferrer,width=960,height=720");

  if (!printWindow) {
    throw new Error("Unable to open a print window on this device.");
  }

  const html = generateClinicalVerificationCertificateHtml(report);

  printWindow.document.open();
  printWindow.document.documentElement.innerHTML = html;
  printWindow.document.close();
  printWindow.focus();
  printWindow.print();
}